import { expect, test } from '@playwright/test'
import { api, expectSuccess, login, pickOption, field } from './helpers'

test('管理员登录并创建员工档案（含账号）', async ({ page }) => {
  await login(page, 'ui')
  await page.locator('[data-test=menu-employees]').click()
  await expect(page.locator('[data-test=employee-table]')).toContainText('平泽唯')
  await page.locator('[data-test=new-employee]').click()
  const dlg = page.locator('[data-test=employee-dialog]')
  await field(dlg, 'emp-name').fill('铃木纯')
  await field(dlg, 'emp-email').fill('jun.e2e@htt.example')
  await pickOption(page, dlg.locator('.el-form-item').filter({ hasText: '部门' }).first().locator('.el-select'), '音乐制作部')
  await field(dlg, 'emp-username').fill('jun')
  await dlg.getByPlaceholder('留空则需管理员重置后启用').fill('JazzBass2026')
  await dlg.locator('[data-test=emp-save]').click()
  await expectSuccess(page, '员工档案已创建')
  await field(page, 'employee-search').fill('铃木纯')
  await field(page, 'employee-search').press('Enter')
  const row = page.locator('[data-test=employee-table] .el-table__body tr').filter({ hasText: '铃木纯' })
  await expect(row).toContainText('HTT0014')
  await expect(row).toContainText('音乐制作部')
  await expect(row).toContainText('试用期')
  // the new account must change its password on first login
  const res = await api(page, 'GET', '/api/users?q=jun')
  expect(res.body.items[0].must_change_password).toBe(true)
  await page.evaluate(() => localStorage.removeItem('doe_token'))
  await login(page, 'jun', 'JazzBass2026')
  await expect(page).toHaveURL(/profile\?force=1/)
  await field(page, 'old-password').fill('JazzBass2026')
  await field(page, 'new-password').fill('JazzBass2027')
  await field(page, 'confirm-password').fill('JazzBass2027')
  await page.locator('[data-test=change-password]').click()
  await expect(page).toHaveURL(/dashboard/)
})
